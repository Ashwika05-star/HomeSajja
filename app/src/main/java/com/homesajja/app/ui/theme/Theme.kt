/** Whether the app is currently drawn with the dark scheme, for the few things (status pills, system bar icons) that need to know. */
val LocalDarkTheme = staticCompositionLocalOf { false }

/** True when [mode] resolves to the dark scheme, given whether the phone itself is in dark mode. */
fun ThemeMode.resolveDark(systemDark: Boolean): Boolean = when (this) {
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
    ThemeMode.SYSTEM -> systemDark
}

@Composable
fun HomeSajjaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    CompositionLocalProvider(LocalDarkTheme provides darkTheme) {
        MaterialTheme(
            colorScheme = if (darkTheme) HomeSajjaDarkColorScheme else HomeSajjaLightColorScheme,
            typography = Typography,
            shapes = AppShapes,
            content = content,
        )
    }
}
